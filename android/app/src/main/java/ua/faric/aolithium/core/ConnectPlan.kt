package ua.faric.aolithium.core

/**
 * Як підключатись до батареї: до «пристрою з пошуку» одразу чи спершу свіжий пошук (T46, v0.4.10).
 *
 * Що показав журнал зв'язку faric 20.10 22:21–22:51 (A26, 0.4.9, телефон удома):
 * - 22:21 фон **спершу пошукав** батарею в ефірі → знайшлась → підключився з першої спроби.
 * - Далі, коли пристрій уже лежав у пам'яті з минулого пошуку (сигнал −88 dBm — теж старий), кожна спроба давала код
 *   Android 133 «ще до з'єднання». Фон робив 2 спроби й здавався: 22:26, 22:31, 22:36, 22:41, 22:46, 22:47 — нема зв'язку.
 *   Екран після 3 таких відмов чекав, доки Android сам підключиться, — і тоді виходило.
 * Висновок: Samsung підключається, коли батарею щойно бачили в ефірі. Старий запис з пошуку — гірший за свіжий пошук.
 *
 * Правило: пристрій з пам'яті беремо лише якщо його бачили щойно ([FRESH_MS]) і це перша спроба. Інакше — свіжий
 * пошук саме цієї адреси. Не знайшли в ефірі — тоді вже старий запис (може, батарея просто рідко «кричить»),
 * у фоні — ще й напряму за адресою, а екран без жодного запису каже «не видно».
 */
object ConnectPlan {
    /** Скільки секунд запис з пошуку вважається свіжим (пошук на головному екрані оновлює його щосекунди). */
    const val FRESH_MS = 15_000L

    enum class First { CACHED, SCAN }

    /** [seenAgoMs] — скільки минуло, відколи батарею бачили в ефірі; null — у пам'яті нема. [retry] — це повторна спроба. */
    fun first(seenAgoMs: Long?, retry: Boolean): First =
        if (!retry && seenAgoMs != null && seenAgoMs in 0..FRESH_MS) First.CACHED else First.SCAN

    enum class AfterScan { FOUND, CACHED, DIRECT, FAIL }

    /** Пошук закінчився: [found] — знайшлась у ефірі; [hasCached] — є старий запис; [quick] — фоновий запис. */
    fun afterScan(found: Boolean, hasCached: Boolean, quick: Boolean): AfterScan = when {
        found -> AfterScan.FOUND
        hasCached -> AfterScan.CACHED
        quick -> AfterScan.DIRECT
        else -> AfterScan.FAIL
    }
}
