package ua.faric.aolithium.core

/**
 * Захисти плати — 16 біт «стану захисту» у відповіді «Основне».
 * Біт = 1 — захист зараз діє (плата вимкнула заряд і/або розряд).
 * Значення бітів — з aiobmsble `docs/jbd_bms.md` і esphome-jbd-bms; пояснення — людською мовою.
 */
enum class Protection(val bit: Int, val title: String, val explain: String) {
    CELL_OVER(0, "Перезаряд комірки", "Якась комірка зарядилась вище межі — плата вимкнула заряд, доки напруга не спаде."),
    CELL_UNDER(1, "Переразряд комірки", "Якась комірка розрядилась нижче межі — плата вимкнула розряд. Потрібна зарядка."),
    PACK_OVER(2, "Перезаряд батареї", "Уся батарея вище межі напруги — заряд вимкнено."),
    PACK_UNDER(3, "Переразряд батареї", "Уся батарея нижче межі напруги — розряд вимкнено. Потрібна зарядка."),
    CHARGE_HOT(4, "Гаряче для заряду", "Температура зависока, щоб заряджати. Заряд вимкнено, доки не охолоне."),
    CHARGE_COLD(5, "Холодно для заряду", "Літій-залізо-фосфат не можна заряджати на морозі. Заряд вимкнено, доки не потеплішає."),
    DISCHARGE_HOT(6, "Гаряче для розряду", "Температура зависока — розряд вимкнено, доки не охолоне."),
    DISCHARGE_COLD(7, "Холодно для розряду", "Занадто холодно навіть для розряду — розряд вимкнено."),
    CHARGE_OVERCURRENT(8, "Завеликий струм заряду", "Зарядний пристрій дає більше, ніж дозволяє плата. Заряд вимкнено на якийсь час."),
    DISCHARGE_OVERCURRENT(9, "Завеликий струм розряду", "Навантаження бере більше, ніж дозволяє плата. Розряд вимкнено на якийсь час."),
    SHORT_CIRCUIT(10, "Коротке замикання", "Плата побачила коротке замикання на виході й вимкнула розряд."),
    IC_ERROR(11, "Помилка мікросхеми плати", "Плата повідомляє про збій своєї мікросхеми вимірювання."),
    SOFTWARE_LOCK(12, "Ключі вимкнено програмно", "Заряд або розряд вимкнено командою з застосунку (не цим — він нічого не вмикає й не вимикає)."),
    ;

    companion object {
        fun fromMask(mask: Int): List<Protection> = entries.filter { mask and (1 shl it.bit) != 0 }

        /** Біти, яких ми не знаємо (13–15): показуємо номером, а не ховаємо. */
        fun unknownBits(mask: Int): List<Int> {
            val known = entries.fold(0) { acc, p -> acc or (1 shl p.bit) }
            return (0..15).filter { mask and (1 shl it) != 0 && known and (1 shl it) == 0 }
        }
    }
}
