package ua.faric.aolithium.core

/**
 * Захисти плати. JBD — 16 біт «стану захисту» у відповіді «Основне» ([bit]); JK BMS — до 32 біт помилок у кадрі 0x02
 * ([jkBit], v0.4). Біт = 1 — захист / збій зараз діє. Де значення в обох платах однакове — та сама назва
 * (тоді й сповіщення однакові). −1 — у цієї плати такого біта нема.
 * Значення бітів — JBD: aiobmsble `docs/jbd_bms.md`, esphome-jbd-bms; JK: esphome-jk-bms (`jk_bms_ble/__init__.py`).
 */
enum class Protection(val bit: Int, val title: String, val explain: String, val jkBit: Int = -1) {
    CELL_OVER(0, "Перезаряд комірки", "Якась комірка зарядилась вище межі — плата вимкнула заряд, доки напруга не спаде.", jkBit = 4),
    CELL_UNDER(1, "Переразряд комірки", "Якась комірка розрядилась нижче межі — плата вимкнула розряд. Потрібна зарядка.", jkBit = 11),
    PACK_OVER(2, "Перезаряд батареї", "Уся батарея вище межі напруги — заряд вимкнено.", jkBit = 5),
    PACK_UNDER(3, "Переразряд батареї", "Уся батарея нижче межі напруги — розряд вимкнено. Потрібна зарядка.", jkBit = 12),
    CHARGE_HOT(4, "Гаряче для заряду", "Температура зависока, щоб заряджати. Заряд вимкнено, доки не охолоне.", jkBit = 8),
    CHARGE_COLD(5, "Холодно для заряду", "Літій-залізо-фосфат не можна заряджати на морозі. Заряд вимкнено, доки не потеплішає.", jkBit = 9),
    DISCHARGE_HOT(6, "Гаряче для розряду", "Температура зависока — розряд вимкнено, доки не охолоне.", jkBit = 15),
    DISCHARGE_COLD(7, "Холодно для розряду", "Занадто холодно навіть для розряду — розряд вимкнено.", jkBit = 27),
    CHARGE_OVERCURRENT(8, "Завеликий струм заряду", "Зарядний пристрій дає більше, ніж дозволяє плата. Заряд вимкнено на якийсь час.", jkBit = 6),
    DISCHARGE_OVERCURRENT(9, "Завеликий струм розряду", "Навантаження бере більше, ніж дозволяє плата. Розряд вимкнено на якийсь час.", jkBit = 13),
    SHORT_CIRCUIT(10, "Коротке замикання", "Плата побачила коротке замикання на виході й вимкнула розряд.", jkBit = 14),
    IC_ERROR(11, "Помилка мікросхеми плати", "Плата повідомляє про збій своєї мікросхеми вимірювання."),
    SOFTWARE_LOCK(12, "Ключі вимкнено програмно", "Заряд або розряд вимкнено командою з застосунку (не цим — він нічого не вмикає й не вимикає)."),

    // ---------- лише JK BMS (esphome-jk-bms, таблиця помилок JK02) ----------
    WIRE_RESISTANCE(-1, "Великий опір дроту комірки", "Плата бачить завеликий опір дроту, яким міряє комірку: ослаб або окиснився контакт. Варто підтягнути / почистити.", jkBit = 0),
    MOS_HOT(-1, "Гарячі ключі плати", "Силові ключі (MOS) плати перегрілись — плата обмежує роботу, доки не охолонуть.", jkBit = 1),
    CELL_COUNT(-1, "Кількість комірок не збігається", "Плата бачить іншу кількість комірок, ніж записано в її налаштуваннях.", jkBit = 2),
    CHARGE_SHORT(-1, "Коротке замикання при заряді", "Плата побачила коротке замикання з боку зарядного й вимкнула заряд.", jkBit = 7),
    COPROCESSOR(-1, "Збій зв'язку всередині плати", "Дві мікросхеми плати не можуть домовитись між собою (помилка допоміжного процесора).", jkBit = 10),
    CHARGE_MOS_FAULT(-1, "Несправність ключа заряду", "Плата повідомляє, що ключ заряду поводиться ненормально.", jkBit = 16),
    DISCHARGE_MOS_FAULT(-1, "Несправність ключа розряду", "Плата повідомляє, що ключ розряду поводиться ненормально.", jkBit = 17),
    DISCHARGE_NOT_ON(-1, "Розряд не ввімкнувся", "Плата спробувала ввімкнути розряд, але не вийшло (часто — завелике навантаження при старті).", jkBit = 20),
    BATTERY_HOT(-1, "Батарея перегріта", "Датчики на комірках показують зависоку температуру.", jkBit = 21),
    SENSOR_FAULT(-1, "Несправний датчик температури", "Один з датчиків температури не відповідає або показує нісенітницю.", jkBit = 22),
    PL_MODULE(-1, "Збій модуля попереднього заряду", "Модуль, що плавно вмикає навантаження (PL / precharge), повідомляє про помилку.", jkBit = 23),
    SC_RELEASE_FAILED(-1, "Не вдалось зняти захист від замикання", "Після короткого замикання плата не змогла сама повернути розряд.", jkBit = 24),
    DISCHARGE_OVERCURRENT_2(-1, "Завеликий струм розряду (рівень 2)", "Навантаження бере набагато більше, ніж дозволяє плата. Розряд вимкнено на якийсь час.", jkBit = 25),
    DISCHARGE_OVERCURRENT_3(-1, "Завеликий струм розряду (рівень 3)", "Навантаження бере набагато більше, ніж дозволяє плата. Розряд вимкнено на якийсь час.", jkBit = 26),
    ;

    companion object {
        fun fromMask(mask: Int): List<Protection> = entries.filter { it.bit >= 0 && mask and (1 shl it.bit) != 0 }

        /** Біти, яких ми не знаємо (13–15): показуємо номером, а не ховаємо. */
        fun unknownBits(mask: Int): List<Int> {
            val known = entries.filter { it.bit >= 0 }.fold(0) { acc, p -> acc or (1 shl p.bit) }
            return (0..15).filter { mask and (1 shl it) != 0 && known and (1 shl it) == 0 }
        }

        /**
         * JK: біти не про батарею — 3 (порожній, колись «датчик струму»), 18 і 28 (GPS), 19 («час змінити пароль» —
         * плата нагадує про пароль за замовчуванням) — не показуємо як захист, бо це не стан батареї.
         */
        val JK_IGNORED_BITS = setOf(3, 18, 19, 28)

        fun fromJkMask(mask: Long): List<Protection> = entries.filter { it.jkBit >= 0 && mask and (1L shl it.jkBit) != 0L }

        fun unknownJkBits(mask: Long): List<Int> {
            val known = entries.filter { it.jkBit >= 0 }.map { it.jkBit }.toSet() + JK_IGNORED_BITS
            return (0..31).filter { mask and (1L shl it) != 0L && it !in known }
        }
    }
}
