package ua.faric.aolithium.core

/**
 * Зони заряду на «спідометрі» (faric 18.10 20:47: «поділиш на сектора… куди не можна заходити стрілці,
 * щоб довше батарея прожила»).
 *
 * Для літій-залізо-фосфату (LiFePO4, як в Aolithium) найбільше шкодить глибокий розряд;
 * постійно тримати 100 % — теж трохи старить, але час від часу заряджати до повної треба:
 * тоді плата вирівнює комірки й уточнює відсоток. Тому верхня зона — помаранчева, не червона.
 */
object Zones {
    enum class Tone { RED, ORANGE, GREEN }

    data class Zone(val from: Int, val to: Int, val tone: Tone, val title: String, val advice: String)

    val ALL = listOf(
        Zone(0, 10, Tone.RED, "Глибокий розряд",
            "Найшкідливіше для батареї. Не доводь сюди: заряди якнайшвидше. Нижче ~10 % плата скоро сама вимкне розряд."),
        Zone(10, 20, Tone.ORANGE, "Мало",
            "Ще можна, але краще вже заряджати. Часто сидіти тут — батарея старіє швидше."),
        Zone(20, 90, Tone.GREEN, "Робоча зона",
            "Тут батарея живе найдовше. Ідеально — працювати між 20 і 90 %."),
        Zone(90, 101, Tone.ORANGE, "Повна",
            "Нормально, але не тримай на 100 % тижнями. Раз на 1–2 тижні дозаряджай до повної — плата вирівняє комірки й уточнить відсоток."),
    )

    fun of(soc: Int): Zone = ALL.first { soc.coerceIn(0, 100) in it.from until it.to }
}
